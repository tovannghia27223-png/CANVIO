const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path'),assert=require('node:assert/strict');
const src=fs.readFileSync(path.join(__dirname,'../../canvio-p125-scrollframes.js'),'utf8');
const html=fs.readFileSync(path.join(__dirname,'../../index.html'),'utf8');
const tag=html.match(/<script id="canvio-lot125f">([\s\S]*?)<\/script>/);
if(!tag)throw new Error('P125.1 embedded lot missing');
assert.equal(tag[1].trim(),src.trim(),'P125.1 source and embedded lot must match');
let captured;
const win={CVZip:{build:async files=>{captured=files;return new Blob(['zip-placeholder'],{type:'application/zip'});}}};
const sb={window:win,document:{readyState:'loading',addEventListener(){}},console,Math,Number,String,Object,Array,Error,RegExp,JSON,Uint8Array,Uint8ClampedArray,Blob,atob};
win.window=win;vm.createContext(sb);vm.runInContext(src,sb,{filename:'canvio-p125-scrollframes.js'});
const api=win.CVScrollFramesP125, good='data:image/jpeg;base64,/9j/AAAA';
(async()=>{
 const validHtml=api.buildHtml([good,good],{width:320,height:180,framePaths:['frames/frame-001.jpg','frames/frame-002.jpg']});
 assert.ok(validHtml.includes('frames/frame-001.jpg')&&validHtml.includes('frames/frame-002.jpg'),'safe relative frame references embedded');
 assert.ok(!validHtml.includes('data:image/jpeg;base64'),'external html does not inline frame payloads');
 const unsafeHtml=api.buildHtml([good,good],{framePaths:['../evil.jpg','https://example.test/a.jpg']});
 assert.ok(!unsafeHtml.includes('../evil.jpg')&&!unsafeHtml.includes('https://example.test/a.jpg'),'untrusted frame paths rejected');
 assert.ok(unsafeHtml.includes('data:image/jpeg;base64'),'unsafe paths fall back to self-contained local frame data');
 const pack=await api.buildPackage([good,good],{width:320,height:180,maxMB:8,title:'Storyboard'});
 assert.ok(pack.blob&&pack.blob.size>0,'ZIP blob produced');
 assert.equal(pack.frameCount,2,'both frames retained');
 assert.equal(pack.fileCount,5,'index, manifest, readme and two external images');
 assert.ok(captured.some(f=>f.name==='index.html'&&f.data.includes('frames/frame-001.jpg')),'ZIP HTML references assets');
 assert.ok(captured.some(f=>f.name==='CANVIO-STORYBOARD-MANIFEST.json'),'manifest included');
 const first=captured.find(f=>f.name==='frames/frame-001.jpg');
 assert.ok(first&&first.data.constructor.name==='Uint8Array'&&first.data.length>0,'binary frame file included');
 assert.equal(pack.manifest.embeddedHtml,false,'manifest identifies split-asset output');
 assert.equal(pack.manifest.maxMB,8,'manifest preserves selected image budget');
 console.log(JSON.stringify({suite:'CANVIO_P125_4_SPLIT_ASSET_PACKAGE',checks:12,frames:pack.frameCount,files:pack.fileCount,bytes:pack.bytes},null,2));
})().catch(e=>{console.error(e);process.exit(1);});
