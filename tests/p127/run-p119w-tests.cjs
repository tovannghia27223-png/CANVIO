'use strict';
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const root=path.resolve(__dirname,'../..');
const source=fs.readFileSync(path.join(root,'canvio-p119-website.js'),'utf8');
const p119=fs.readFileSync(path.join(root,'canvio-p119-easing.js'),'utf8');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const map=JSON.parse(fs.readFileSync(path.join(root,'tests/p143/source-module-map.json'),'utf8'));
function assert(name,value){if(!value)throw new Error('FAIL '+name);console.log('PASS '+name);}
const document={readyState:'loading',addEventListener(){},getElementById(){return null;}};
const context={console,Math,Number,String,Array,Object,JSON,document,MutationObserver:undefined};
context.window=context;context.document=document;
vm.createContext(context);
vm.runInContext(p119,context,{filename:'canvio-p119-easing.js'});
vm.runInContext(source,context,{filename:'canvio-p119-website.js'});
const api=context.CVWebsiteEasingP119;
if(!api)throw new Error('P119.4 API not registered');
const checks=api.tests();
assert('P119 single shared registry available',checks.sharedRegistryAvailable);
assert('all six shared presets exposed in stable order',checks.sixP119PresetsExposed);
assert('all preset values round-trip as canonical cubic-bezier CSS',checks.allPresetValuesCanonicalBezier);
assert('spring linear() cannot be misrepresented as cubic-bezier',checks.springLinearSyntaxRejected);
assert('no parallel preset registry is introduced',checks.noParallelPresetRegistry);
assert('Website Motion Builder remains the required owner',checks.existingWebsiteMotionOwnerRequired);
assert('custom Motion cubic-bezier is accepted',api.canonicalCurve('cubic-bezier(0.1,0.2,0.3,0.4)')==='cubic-bezier(0.1,0.2,0.3,0.4)');
assert('non-Bezier timing functions are rejected',api.canonicalCurve('linear(0,0.5,1)')===null);
assert('malformed CSS easing is rejected',api.canonicalCurve('cubic-bezier(9,0,9,1)')===null);
const inline=(html.match(/<script\b[^>]*id=["']canvio-lot119w["'][^>]*>([\s\S]*?)<\/script>/i)||[])[1]||'';
assert('canonical inline source is present',!!inline);
assert('standalone and canonical inline sources match',inline.trim().replace(/\r\n/g,'\n')===source.trim().replace(/\r\n/g,'\n'));
const pair=map.modules.filter(x=>x.source==='canvio-p119-website.js'&&x.scriptId==='canvio-lot119w');
assert('P143 registry includes exactly one P119.4 source pair',pair.length===1&&map.totalModules===34);
assert('Website easing change preserves reduced-motion export owner',html.includes('canvio-motion-runtime')||html.includes('CVWebsiteMotionBuilder'));
console.log('P119.4 PASS: 13 assertions');
