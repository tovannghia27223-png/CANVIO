import threading, http.server, socketserver, functools, os, shutil
from playwright.sync_api import sync_playwright
ROOT=os.path.abspath(os.path.join(os.path.dirname(__file__),'..','..'))
class Quiet(http.server.SimpleHTTPRequestHandler):
    def log_message(self,*a): pass
server=socketserver.ThreadingTCPServer(('127.0.0.1',0),functools.partial(Quiet,directory=ROOT));server.daemon_threads=True
threading.Thread(target=server.serve_forever,daemon=True).start()
url='http://127.0.0.1:%d/index.html'%server.server_address[1]
checks=[]; errors=[]
def ck(name,ok):
    checks.append((name,bool(ok))); print(('PASS ' if ok else 'FAIL ')+name)
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path=shutil.which('google-chrome') or shutil.which('chromium'),headless=True,args=['--no-sandbox','--disable-gpu'])
    page=browser.new_page(viewport={'width':1440,'height':900})
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.add_init_script("(function(){const s={};const st={getItem:k=>Object.prototype.hasOwnProperty.call(s,k)?s[k]:null,setItem:(k,v)=>s[k]=String(v),removeItem:k=>delete s[k],clear:()=>Object.keys(s).forEach(k=>delete s[k]),key:i=>Object.keys(s)[i]||null,get length(){return Object.keys(s).length}};try{Object.defineProperty(window,'localStorage',{value:st,configurable:true});Object.defineProperty(window,'sessionStorage',{value:st,configurable:true})}catch(e){}})();")
    page.goto(url,wait_until='domcontentloaded',timeout=120000)
    page.wait_for_function("!!window.CVEditorInputP235",timeout=90000)
    page.evaluate("CV.go('videoEngine')")
    page.wait_for_function("!!document.querySelector('#cv231-shell-videoEngine:not([hidden])')")
    before=page.evaluate("CV.engines.video._state().clips.length")
    page.evaluate("CV.engines.video.addText()")
    after=page.evaluate("CV.engines.video._state().clips.length")
    ck('Video Engine add-text action creates one native clip',after==before+1)
    page.keyboard.press('Control+z')
    ck('Ctrl+Z routes to native timeline undo',page.evaluate("n=>CV.engines.video._state().clips.length===n",before))
    page.keyboard.press('Control+y')
    ck('Ctrl+Y routes to native timeline redo',page.evaluate("n=>CV.engines.video._state().clips.length===n",after))
    page.keyboard.press('Space')
    ck('Space starts the native video playhead',page.evaluate("CV.engines.video._state().playing===true"))
    page.keyboard.press('Space')
    ck('Space pauses the native video playhead',page.evaluate("CV.engines.video._state().playing===false"))
    page.keyboard.press('Control+d')
    duplicate_count=page.evaluate("CV.engines.video._state().clips.length")
    ck('Ctrl+D duplicates the selected native clip',duplicate_count==after+1)
    page.keyboard.press('Delete')
    ck('Delete removes the selected native clip',page.evaluate("n=>CV.engines.video._state().clips.length===n",after))
    page.keyboard.press('Alt+3')
    ck('Alt+3 focuses the active editor inspector region',page.evaluate("document.querySelector('#cv231-shell-videoEngine .cv231-props').contains(document.activeElement)"))
    page.locator('#vtWhisperLang').focus()
    was=page.evaluate("CV.engines.video._state().playing")
    page.keyboard.press('Space')
    ck('Typing/select controls retain native keyboard behavior',page.evaluate("v=>CV.engines.video._state().playing===v",was))
    page.evaluate("()=>{const api=CV.engines.video,original=api.save;window.__saveCount=0;api.save=function(){window.__saveCount++;return original.apply(api,arguments)}}")
    page.locator('#cv231-shell-videoEngine .cv231-ident').click()
    page.keyboard.press('Control+s')
    ck('Ctrl+S invokes the existing Video Engine save owner',page.evaluate("window.__saveCount===1"))
    ck('P235 exports its scoped shortcut contract',page.evaluate("CVEditorInputP235.tests().scopedPages===true && CVEditorInputP235.tests().nativeCanvasGestureNotOverridden===true"))
    ck('No uncaught JavaScript page errors',len(errors)==0)
    if errors: print('PAGE_ERRORS '+repr(errors))
    browser.close()
    server.shutdown();server.server_close()
failed=[n for n,v in checks if not v]
print('%d/%d P235 browser assertions passed'%(len(checks)-len(failed),len(checks)))
if failed: raise SystemExit('Failures: '+', '.join(failed))
if errors: raise SystemExit('Uncaught page errors: '+repr(errors))
