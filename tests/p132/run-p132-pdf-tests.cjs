'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'../..');
const source=fs.readFileSync(path.join(root,'canvio-p132-pdf-import.js'),'utf8');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const match=html.match(/<script id="canvio-lot132pdf">([\s\S]*?)<\/script>/);
assert.ok(match,'P132.1 must be embedded in canonical index.html');
assert.equal(match[1].replace(/\r\n?/g,'\n').trim(),source.replace(/\r\n?/g,'\n').trim(),'standalone/embedded source parity');
new vm.Script(source,{filename:'canvio-p132-pdf-import.js'});
const listeners={};
const page={addEventListener:(name,fn)=>{listeners[name]=fn;},head:{appendChild(){}},body:{appendChild(){}},baseURI:'http://127.0.0.1/',readyState:'loading',getElementById:()=>null,createElement:()=>({})};
const sandbox={window:{document:page,URL,Promise,Uint8Array,DataView,ArrayBuffer,Number,String,Object,Math,Date,Error},document:page,URL,Promise,Uint8Array,DataView,ArrayBuffer,Number,String,Object,Math,Date,Error,console};
sandbox.window.window=sandbox.window;
vm.createContext(sandbox);
vm.runInContext(source,sandbox);
const api=sandbox.window.CVPdfImportP132;
assert.ok(api,'P132.1 API');
assert.equal(api.version,'132.1.0');
const checks=api.tests();
for(const [name,passed] of Object.entries(checks))assert.equal(passed,true,'P132.1: '+name);
assert.equal(Object.keys(checks).length,11);
assert.ok(source.includes("new URL('./assets/vendor/pdfjs/pdf.mjs'"),'main PDF.js entry must be same-origin');
assert.ok(source.includes("new URL('./assets/vendor/pdfjs/pdf.worker.mjs'"),'PDF worker must be same-origin');
assert.ok(source.includes("standardFontDataUrl: new URL('./assets/vendor/pdfjs/standard_fonts/'"),'standard fonts must be local');
assert.ok(source.includes("cMapUrl: new URL('./assets/vendor/pdfjs/cmaps/'"),'CMaps must be local');
assert.ok(source.includes('isEvalSupported: false'),'PDF JavaScript evaluation must be disabled');
assert.ok(source.includes('enableXfa: false'),'XFA must be disabled');
assert.ok(source.includes('MAX_FILE_BYTES = 30 * 1024 * 1024'));
assert.ok(source.includes('MAX_PAGES = 500'));
assert.ok(source.includes('MAX_PIXELS = 16000000'));
assert.ok(source.includes("target.dispatchEvent(new root.Event('change', { bubbles: true }))"),'handoff must reuse Pixel Atelier file input');
assert.ok(!/https?:\/\/(?:cdn|unpkg|esm\.sh)/i.test(source),'no remote PDF runtime');
console.log(JSON.stringify({suite:'P132.1 local PDF page import contracts',passed:checks,sourceParity:true,securityBounds:true},null,2));
