'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {scanHtml}=require('./build-asset-dependency-inventory.cjs');
const fixture='<!doctype html><html><head><link rel="stylesheet" href="app.css"><style id="theme">.a{color:red}</style></head><body><main id="root" style="display:grid;gap:8px"><template id="card"><article><b>Hi</b></article></template><script id="json" type="application/json">{"ok":true}</script><script id="loader">const root=document.querySelector("#root");root.innerHTML=`<article>markup</article>`;const s=document.createElement("script");s.src="/lazy.js";document.head.appendChild(s);const w=new Worker("/worker.js");</script></main></body></html>';
const r=scanHtml(fixture);
assert.equal(r.styleBlockCount,1);
assert.equal(r.inlineStyleAttributeCount,1);
assert.equal(r.htmlTemplateElementCount,1);
assert.equal(r.inertScriptPayloadCount,1);
assert.ok(r.htmlTemplateSignalCount>=1);
assert.equal(r.stylesheetLinkCount,1);
assert.equal(r.scriptBlockCount,2);
assert.ok(r.dynamicLoaderSignalCount>=3);
assert.equal(r.duplicateElementIds.length,0);
assert.equal(r.templateBlocks.find(x=>x.kind!=='inert-script-payload').id,'card');
assert.equal(r.styleBlocks[0].id,'theme');
const canonical=scanHtml(fs.readFileSync('index.html','utf8'));
assert.ok(canonical.scriptBlockCount>=150);
assert.ok(canonical.styleBlockCount>0);
assert.ok(canonical.inlineStyleAttributeCount>0);
assert.equal(canonical.htmlTemplateElementCount,0);
assert.ok(canonical.inertScriptPayloadCount>0);
assert.ok(canonical.htmlTemplateSignalCount>0);
assert.ok(canonical.stylesheetLinkCount>0);
