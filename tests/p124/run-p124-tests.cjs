'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const source=fs.readFileSync(path.resolve(__dirname,'../../canvio-p124-autolayout.js'),'utf8');
const html=fs.readFileSync(path.resolve(__dirname,'../../index.html'),'utf8');
const id='canvio-lot124';
const match=html.match(new RegExp('<script id="'+id+'">([\\s\\S]*?)<\\/script>'));
assert.ok(match,'P124 must be integrated into canonical index.html');
assert.equal(match[1].trim(),source.trim(),'P124 standalone/embedded source parity');
const sandbox={window:{},document:{readyState:'loading',addEventListener(){}},console,Promise,Math,Number,String,Object,Array,RegExp,isFinite};
sandbox.window.window=sandbox.window;
vm.createContext(sandbox);
vm.runInContext(source,sandbox);
const api=sandbox.window.CVAutoLayoutP124;
assert.ok(api,'P124 API');
const checks=api.tests();
for(const [name,passed] of Object.entries(checks)) assert.equal(passed,true,'P124: '+name);
assert.equal(Object.keys(checks).length,24);
assert.equal(api.inspect().layouts.length,5);
assert.equal(api.render('grid',{columns:4}).match(/data-canvio-component="card"/g).length,4);
assert.match(api.render('grid',{desktopColumns:4,mobileBreakpoint:680,tabletBreakpoint:1024}),/grid-template-columns:repeat\(4,minmax\(0,1fr\)\)/);
assert.match(api.render('grid',{desktopColumns:4,mobileBreakpoint:680,tabletBreakpoint:1024}),/@media\(max-width:680px\)/);
assert.match(api.render('grid',{desktopColumns:4,mobileBreakpoint:680,tabletBreakpoint:1024}),/@media\(max-width:1024px\)/);
assert.throws(()=>api.render('unknown'),/không hợp lệ/i);
(async()=>{
  const missing=await api.insert('grid');
  assert.equal(missing.ok,false);
  assert.equal(missing.inserted,false);
  let inserted='',saved=0;
  sandbox.window.CVWeb={addComponents(markup){inserted=markup;}};
  sandbox.window.CV={engines:{web:{save(){saved++;}}}};
sandbox.CV=sandbox.window.CV; // Browser global binding mirrors window.CV.
  sandbox.window.CVWeb.addComponents=()=>false;
  const rejected=await api.insert('grid');
  assert.equal(rejected.ok,false);
  assert.equal(rejected.inserted,false);
  sandbox.window.CVWeb.addComponents=(markup)=>{inserted=markup;};
  const success=await api.insert('grid',{columns:3,variant:'soft'});
  assert.equal(success.ok,true);
  assert.equal(success.saved,true);
  assert.equal(saved,1);
  assert.match(inserted,/data-canvio-auto-layout="grid"/);
  sandbox.window.CV.engines.web.save=()=>false;
  const rejectedSave=await api.insert('card');
  assert.equal(rejectedSave.ok,false);
  assert.equal(rejectedSave.inserted,true);
  assert.equal(rejectedSave.saved,false);
  sandbox.window.CV.engines.web.save=()=>{throw new Error('quota');};
  const failed=await api.insert('card');
  assert.equal(failed.ok,false);
  assert.equal(failed.inserted,true);
  assert.equal(failed.saved,false);
  const badSelector=(()=>{try{api.selectedLayoutCss('body','grid',{});return false;}catch(e){return true;}})();
  assert.equal(badSelector,true);
  assert.match(api.selectedLayoutCss('.cv-p124-selected-node','grid',{desktopColumns:4,tabletColumns:2,mobileColumns:1}),/@media\(max-width:960px\)/);
  assert.match(api.selectedVariantCss('.cv-p124-selected-node','elevated'),/data-canvio-variant="elevated"/);
  const rules=[];
  const selected={classes:[],attributes:{},getId(){return 'chosen-node';},is(){return false;},addClass(name){if(!this.classes.includes(name))this.classes.push(name);},addAttributes(values){Object.assign(this.attributes,values);}};
  sandbox.window.CVWeb={getSelected(){return selected;},Css:{setRule(selector,style,options){rules.push({selector,style,options:options||null});}}};
  sandbox.window.CV.engines.web.save=()=>{saved++;return true;};
  const appliedLayout=await api.applyLayoutToSelected('grid',{desktopColumns:4,tabletColumns:2,mobileColumns:1,variant:'soft'});
  assert.equal(appliedLayout.ok,true);
  assert.equal(appliedLayout.saved,true);
  assert.equal(selected.attributes['data-canvio-auto-layout'],'grid');
  assert.equal(selected.attributes['data-canvio-variant'],'soft');
  assert.equal(rules.length,3);
  assert.ok(rules[0].style['grid-template-columns'].includes('4'));
  assert.ok(rules[1].options.atRuleParams.includes('960px'));
  const appliedVariant=await api.applyVariantToSelected('elevated');
  assert.equal(appliedVariant.ok,true);
  assert.equal(selected.attributes['data-canvio-variant'],'elevated');
  assert.equal(rules.length,4);
  assert.equal((await api.applyLayoutToSelected('card')).ok,false);
  assert.equal((await api.applyVariantToSelected('unknown')).ok,false);
  console.log(JSON.stringify({suite:'P124 responsive auto-layout and component variants',passed:55,total:55,checks},null,2));
})().catch(error=>{console.error(error);process.exitCode=1;});
